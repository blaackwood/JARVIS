def _schedule_windows(target_dt: datetime, task_name: str,
                      script_path: Path, message: str) -> str:
    python_exe = Path(sys.executable)
    pythonw = python_exe.parent / "pythonw.exe"
    if pythonw.exists():
        python_exe = pythonw

    xml_path = _scripts_dir() / f"{task_name}.xml"
    xml_content = (
        '<?xml version="1.0" encoding="UTF-16"?>\n'
        '<Task version="1.2" xmlns="http://schemas.microsoft.com/windows/2004/02/mit/task">\n'
        '  <RegistrationInfo><Description>J.A.R.V.I.S Reminder</Description></RegistrationInfo>\n'
        '  <Triggers><TimeTrigger>\n'
        f'    <StartBoundary>{target_dt.strftime("%Y-%m-%dT%H:%M:%S")}</StartBoundary>\n'
        '    <Enabled>true</Enabled>\n'
        '  </TimeTrigger></Triggers>\n'
        '  <Actions><Exec>\n'
        f'    <Command>{python_exe}</Command>\n'
        f'    <Arguments>"{script_path}"</Arguments>\n'
        '  </Exec></Actions>\n'
        '  <Settings>\n'
        '    <MultipleInstancesPolicy>IgnoreNew</MultipleInstancesPolicy>\n'
        '    <DisallowStartIfOnBatteries>false</DisallowStartIfOnBatteries>\n'
        '    <StopIfGoingOnBatteries>false</StopIfGoingOnBatteries>\n'
        '    <StartWhenAvailable>true</StartWhenAvailable>\n'
        '    <ExecutionTimeLimit>PT5M</ExecutionTimeLimit>\n'
        '    <Enabled>true</Enabled>\n'
        '  </Settings>\n'
        '  <Principals><Principal>\n'
        '    <LogonType>InteractiveToken</LogonType>\n'
        '    <RunLevel>LeastPrivilege</RunLevel>\n'
        '  </Principal></Principals>\n'
        '</Task>'
    )

    xml_path.write_text(xml_content, encoding="utf-16")

    result = subprocess.run(
        ["schtasks", "/Create", "/TN", task_name, "/XML", str(xml_path), "/F"],
        capture_output=True, text=True, encoding="utf-8", errors="replace", **_CNW,
    )

    try:
        xml_path.unlink(missing_ok=True)
    except Exception:
        pass

    if result.returncode != 0:
        script_path.unlink(missing_ok=True)
        err = (result.stderr or result.stdout).strip()
        print(f"[Reminder] ❌ schtasks: {err}")
        return ""  

    return f"schtasks:{task_name}"


def _schedule_mac(target_dt: datetime, task_name: str,
                  script_path: Path) -> str:
    agents_dir = Path.home() / "Library" / "LaunchAgents"
    agents_dir.mkdir(parents=True, exist_ok=True)

    label     = f"com.jarvis.reminder.{task_name}"
    plist_path = agents_dir / f"{label}.plist"

    plist_content = f"""<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN"
  "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0">
<dict>
  <key>Label</key>             <string>{label}</string>
  <key>ProgramArguments</key>
  <array>
    <string>{sys.executable}</string>
    <string>{script_path}</string>
  </array>
  <key>StartCalendarInterval</key>
  <dict>
    <key>Year</key>   <integer>{target_dt.year}</integer>
    <key>Month</key>  <integer>{target_dt.month}</integer>
    <key>Day</key>    <integer>{target_dt.day}</integer>
    <key>Hour</key>   <integer>{target_dt.hour}</integer>
    <key>Minute</key> <integer>{target_dt.minute}</integer>
  </dict>
  <key>RunAtLoad</key>         <false/>
  <key>StandardOutPath</key>   <string>/dev/null</string>
  <key>StandardErrorPath</key> <string>/dev/null</string>
</dict>
</plist>
"""
    plist_path.write_text(plist_content, encoding="utf-8")
    plist_path.chmod(0o644)

    result = subprocess.run(
        ["launchctl", "load", str(plist_path)],
        capture_output=True, text=True, encoding="utf-8", errors="replace",
    )

    if result.returncode != 0:
        plist_path.unlink(missing_ok=True)
        script_path.unlink(missing_ok=True)
        print(f"[Reminder] ❌ launchctl: {result.stderr.strip()}")
        return ""

    return f"launchd:{label}"


def _schedule_linux(target_dt: datetime, task_name: str,
                    script_path: Path) -> str:

    if shutil.which("systemd-run"):
        on_calendar = target_dt.strftime("%Y-%m-%d %H:%M:00")
        result = subprocess.run(
            [
                "systemd-run",
                "--user",
                f"--on-calendar={on_calendar}",
                f"--unit={task_name}",
                "--",
                sys.executable, str(script_path),
            ],
            capture_output=True, text=True, encoding="utf-8", errors="replace",
        )
        if result.returncode == 0:
            return task_name
        print(f"[Reminder] ⚠️ systemd-run failed: {result.stderr.strip()}, trying 'at'")

    if shutil.which("at"):
        at_time = target_dt.strftime("%H:%M %Y-%m-%d")
        cmd_str = f"{sys.executable} {script_path}\n"
        result  = subprocess.run(
            ["at", at_time],
            input=cmd_str, capture_output=True, text=True, encoding="utf-8", errors="replace",
        )
        if result.returncode == 0:
            return task_name
        print(f"[Reminder] ❌ at: {result.stderr.strip()}")
        return ""

    print("[Reminder] ❌ Neither systemd-run nor at found on this Linux system.")
    return ""

def _add_spoken_routine(message: str, target_dt: datetime, reminder_id: str,
                        task_name: str, script_path: Path, os_name: str,
                        scheduler_id: str):
    """Use the existing routine store as the canonical reminder record.

    The Windows/OS notification is a delivery mechanism attached to this
    record, not a second agenda with an unrelated identity.
    """
    from core.routines import desktop
    eng = desktop.engine()
    if eng is None:
        raise RuntimeError("the routine store is unavailable; the local reminder cannot be saved safely")
    meta = {
        "id": reminder_id, "status": "open", "due_ts": target_dt.timestamp(),
        "message": message[:200], "os_name": os_name,
        "task_name": task_name, "script_path": str(script_path),
        "scheduler_id": scheduler_id, "created_at": time.time(),
    }
    return eng.add(
        name=message[:60] or "Reminder", kind="say", text=message,
        trigger={"type": "time", "rule": {"type": "once", "at_ts": target_dt.timestamp()}},
        options={"jarvis_reminder": meta}, source="reminder",
        next_ts=target_dt.timestamp(),
    )


def _safe_script_path(value: str, task_name: str) -> Path | None:
    """Only remove a generated script inside JARVIS's private reminder folder."""
    try:
        path = Path(str(value or "")).resolve()
        folder = _scripts_dir().resolve()
        if path.parent != folder or path.name != f"{task_name}.py":
            return None
        if not task_name.startswith("JARVISReminder_"):
            return None
        return path
    except Exception:
        return None


def _cancel_os_schedule(meta: dict) -> tuple[bool, str]:
    """Cancel exactly the OS job recorded on a JARVIS reminder."""
    task_name = str(meta.get("task_name") or "")
    scheduler_id = str(meta.get("scheduler_id") or "")
    os_name = str(meta.get("os_name") or "windows")
    if not task_name.startswith("JARVISReminder_") or not scheduler_id:
        return False, "this reminder has no verified scheduler identifier; left it unchanged"
    try:
        if os_name == "windows":
            query = subprocess.run(
                ["schtasks", "/Query", "/TN", task_name], capture_output=True,
                text=True, encoding="utf-8", errors="replace", **_CNW,
            )
            if query.returncode == 0:
                result = subprocess.run(
                    ["schtasks", "/Delete", "/TN", task_name, "/F"],
                    capture_output=True, text=True, encoding="utf-8", errors="replace", **_CNW,
                )
                verify = subprocess.run(
                    ["schtasks", "/Query", "/TN", task_name], capture_output=True,
                    text=True, encoding="utf-8", errors="replace", **_CNW,
                )
                if verify.returncode == 0:
                    return False, (result.stderr or result.stdout or "Windows did not delete the task").strip()
            else:
                missing = (query.stderr or query.stdout or "").lower()
                if not any(token in missing for token in (
                    "cannot find the file specified", "cannot find the path specified",
                    "cannot find the task", "does not exist",
                )):
                    return False, (query.stderr or query.stdout or "could not verify the Windows task").strip()
        elif os_name == "mac":
            label = scheduler_id.removeprefix("launchd:")
            if label != f"com.jarvis.reminder.{task_name}":
                return False, "the saved launchd label did not match this reminder"
            plist = Path.home() / "Library" / "LaunchAgents" / f"{label}.plist"
            if plist.exists():
                result = subprocess.run(
                    ["launchctl", "unload", str(plist)], capture_output=True,
                    text=True, encoding="utf-8", errors="replace",
                )
                if result.returncode != 0:
                    return False, (result.stderr or result.stdout or "launchctl refused to unload the reminder").strip()
                plist.unlink(missing_ok=True)
        elif scheduler_id.startswith("at:"):
            job_id = scheduler_id.split(":", 1)[1]
            if not job_id.isdigit():
                return False, "the saved at job identifier is invalid"
            result = subprocess.run(["atrm", job_id], capture_output=True, text=True,
                                    encoding="utf-8", errors="replace")
            if result.returncode != 0:
                return False, (result.stderr or result.stdout or "atrm failed").strip()
        else:
            unit = scheduler_id.removeprefix("systemd:")
            if unit != task_name:
                return False, "the saved systemd unit did not match this reminder"
            result = subprocess.run(
                ["systemctl", "--user", "stop", f"{unit}.timer"], capture_output=True,
                text=True, encoding="utf-8", errors="replace",
            )
            if result.returncode != 0:
                probe = subprocess.run(
                    ["systemctl", "--user", "is-active", f"{unit}.timer"], capture_output=True,
                    text=True, encoding="utf-8", errors="replace",
                )
                if (probe.stdout or "").strip() == "active":
                    return False, (result.stderr or result.stdout or "systemd timer is still active").strip()
        script = _safe_script_path(meta.get("script_path", ""), task_name)
        if script is not None:
            script.unlink(missing_ok=True)
            script.with_suffix(".fired").unlink(missing_ok=True)
        return True, "cancelled"
    except Exception as exc:
        return False, f"{type(exc).__name__}: {str(exc)[:140]}"


def _cloud_reminder_state(meta: dict, state: str) -> tuple[bool, str]:
    if not meta.get("cloud_synced"):
        return True, "not paired"
    agent = sys.modules.get("plugins.cloud_agent")
    callback = getattr(agent, "set_reminder_state", None) if agent else None
    if not callable(callback):
        return False, "the cloud link is no longer loaded; local state was left unchanged"
    return callback(str(meta.get("id") or ""), state)


def _reschedule_os_schedule(meta: dict) -> tuple[bool, str, dict]:
    task_name = str(meta.get("task_name") or "")
    due_ts = float(meta.get("due_ts") or 0)
    if not task_name.startswith("JARVISReminder_") or due_ts <= time.time():
        return False, "there is no future local notification to restore", dict(meta)
    os_name = _get_os()
    message = _sanitise(meta.get("message") or "Reminder")
    script_path = _write_notify_script(task_name, message, os_name)
    due_dt = datetime.fromtimestamp(due_ts)
    try:
        if os_name == "windows":
            scheduler_id = _schedule_windows(due_dt, task_name, script_path, message)
        elif os_name == "mac":
            scheduler_id = _schedule_mac(due_dt, task_name, script_path)
        else:
            scheduler_id = _schedule_linux(due_dt, task_name, script_path)
    except Exception as exc:
        script_path.unlink(missing_ok=True)
        return False, f"{type(exc).__name__}: {str(exc)[:120]}", dict(meta)
    if not scheduler_id:
        script_path.unlink(missing_ok=True)
        return False, "the operating system did not accept the notification", dict(meta)
    updated = dict(meta)
    updated.update({"os_name": os_name, "script_path": str(script_path),
                    "scheduler_id": scheduler_id})
    return True, "rescheduled", updated


def set_reminder_state(reminder_id: str, state: str) -> tuple[bool, str]:
    """Change the canonical record only after its paired deliveries agree."""
    from core.routines import desktop
    eng = desktop.engine()
    if eng is None:
        return False, "the routine store is not running"
    routine = next((r for r in eng.list()
                    if r.get("source") == "reminder"
                    and ((r.get("options") or {}).get("jarvis_reminder") or {}).get("id") == reminder_id), None)
    if routine is None:
        return False, "no reminder with that id"
    options = dict(routine.get("options") or {})
    meta = dict(options.get("jarvis_reminder") or {})
    state = str(state or "").lower()
    if state not in {"open", "done", "cancelled"}:
        return False, "state must be open, done or cancelled"
    current = str(meta.get("status") or "open")
    if current == state:
        return True, f"already {state}"

    due_ts = float(meta.get("due_ts") or routine.get("next_ts") or 0)
    if state in {"done", "cancelled"}:
        # Cancel the remote copy first. If the local OS refuses cancellation,
        # compensate by reopening the cloud item before returning a failure.
        cloud_ok, cloud_detail = _cloud_reminder_state(meta, state)
        if not cloud_ok:
            return False, f"cloud copy could not be {state}: {cloud_detail}"
        local_cancelled = False
        if current not in {"done", "cancelled"} and meta.get("scheduler_id"):
            ok, detail = _cancel_os_schedule(meta)
            if not ok:
                rolled_back, rollback_detail = _cloud_reminder_state(meta, "open")
                if not rolled_back:
                    return False, (f"local notification remains active ({detail}); cloud rollback also failed "
                                   f"({rollback_detail})")
                return False, f"could not {state} safely: {detail}"
            local_cancelled = True
        meta["status"] = state
        meta["completed_at" if state == "done" else "cancelled_at"] = time.time()
        options["jarvis_reminder"] = meta
        try:
            eng.update(routine["id"], enabled=False, options=options)
        except Exception as exc:
            # Compensate both deliveries if persistence fails after they were
            # changed. Never leave the UI claiming a change that was not saved.
            cloud_rolled_back, cloud_error = _cloud_reminder_state(meta, "open")
            local_rolled_back = True
            if local_cancelled:
                local_rolled_back, local_error, restored = _reschedule_os_schedule(meta)
                if local_rolled_back:
                    try:
                        eng.update(routine["id"], options={"jarvis_reminder": restored})
                    except Exception:
                        pass
                else:
                    local_error = local_error
            else:
                local_error = ""
            return False, (f"could not save the reminder state ({type(exc).__name__}); "
                           f"cloud rollback={'ok' if cloud_rolled_back else cloud_error}; "
                           f"local rollback={'ok' if local_rolled_back else local_error}")
        return True, state

    # Reopening a future reminder restores the local notification, then the
    # cloud copy. If the cloud refuses, remove the local job we just created.
    if due_ts > time.time():
        ok, detail, restored = _reschedule_os_schedule(meta)
        if not ok:
            return False, f"could not restore the local notification: {detail}"
        cloud_ok, cloud_detail = _cloud_reminder_state(meta, "open")
        if not cloud_ok:
            _cancel_os_schedule(restored)
            return False, f"could not reopen the cloud copy: {cloud_detail}"
        meta = restored
        meta.update({"status": "open", "reopened_at": time.time()})
        options["jarvis_reminder"] = meta
        try:
            eng.update(routine["id"], enabled=True, options=options)
        except Exception as exc:
            cloud_rolled_back, rollback_detail = _cloud_reminder_state(meta, current)
            local_rolled_back, local_detail, _ = _cancel_os_schedule(meta)
            return False, (f"could not save reopened reminder ({type(exc).__name__}); "
                           f"cloud rollback={'ok' if cloud_rolled_back else rollback_detail}; "
                           f"local rollback={'ok' if local_rolled_back else local_detail}")
        return True, "reopened and notifications rescheduled"

    cloud_ok, cloud_detail = _cloud_reminder_state(meta, "open")
    if not cloud_ok:
        return False, f"could not reopen the cloud copy: {cloud_detail}"
    meta.update({"status": "open", "reopened_at": time.time(), "overdue": True})
    options["jarvis_reminder"] = meta
    try:
        eng.update(routine["id"], enabled=False, options=options)
    except Exception as exc:
        rollback_ok, rollback_detail = _cloud_reminder_state(meta, current)
        return False, (f"could not save reopened reminder ({type(exc).__name__}); "
                       f"cloud rollback={'ok' if rollback_ok else rollback_detail}")
    return True, "reopened as an overdue commitment; its past notification was not replayed"

def _list_reminders() -> str:
    from core.routines import desktop
    eng = desktop.engine()
    if eng is None:
        return "The reminder list is unavailable because routines are not running."
    rows = []
    for r in eng.list():
        if r.get("source") != "reminder":
            continue
        meta = (r.get("options") or {}).get("jarvis_reminder") or {}
        due = datetime.fromtimestamp(float(meta.get("due_ts") or r.get("next_ts") or 0))
        status = str(meta.get("status") or "open")
        rows.append((due.timestamp(), f"{meta.get('id') or r['id']} [{status}] {due:%Y-%m-%d %H:%M} ? {r.get('text','')[:100]}"))
    rows.sort(key=lambda x: (x[0], "[done]" in x[1]))
    return "\n".join(row for _, row in rows) or "No reminders."


def reminder(parameters: dict, response=None, player=None, session_memory=None) -> str:
    """Create a timed reminder or manage an existing reminder by its stable ID."""
    params = dict(parameters or {})
    action = str(params.get("action") or "create").strip().lower()
    if action == "list":
        return _list_reminders()
    if action in {"complete", "done", "reopen", "cancel"}:
        rid = str(params.get("id") or "").strip()
        if not rid:
            return "I need the reminder id. Use action=list to see reminder ids."
        state = "open" if action == "reopen" else "cancelled" if action == "cancel" else "done"
        ok, detail = set_reminder_state(rid, state)
        return f"Reminder {state}: {rid}. {detail}" if ok else f"Reminder unchanged: {detail}."
    if action != "create":
        return "Unknown reminder action. Use create, list, complete, reopen or cancel."

    date_str = str(params.get("date") or "").strip()
    time_str = str(params.get("time") or "").strip()
    message = str(params.get("message") or "Reminder").strip()
    if not date_str or not time_str:
        return "I need both a date and a time to set a reminder."
    try:
        target_dt = datetime.strptime(f"{date_str} {time_str}", "%Y-%m-%d %H:%M")
    except ValueError:
        return "I couldn't parse that date or time. Please use YYYY-MM-DD and HH:MM."
    if target_dt <= datetime.now():
        return "That time has already passed - I can't set a reminder in the past."

    os_name = _get_os()
    safe_msg = _sanitise(message)
    reminder_id = uuid.uuid4().hex[:12]
    task_name = f"JARVISReminder_{reminder_id}"
    try:
        script_path = _write_notify_script(task_name, safe_msg, os_name)
    except Exception as exc:
        return f"Could not prepare the reminder script: {type(exc).__name__}: {str(exc)[:120]}"
    try:
        if os_name == "windows":
            scheduler_id = _schedule_windows(target_dt, task_name, script_path, safe_msg)
        elif os_name == "mac":
            scheduler_id = _schedule_mac(target_dt, task_name, script_path)
        else:
            scheduler_id = _schedule_linux(target_dt, task_name, script_path)
    except Exception as exc:
        script_path.unlink(missing_ok=True)
        return f"Something went wrong while scheduling the reminder: {type(exc).__name__}: {str(exc)[:120]}"
    if not scheduler_id:
        script_path.unlink(missing_ok=True)
        return "I couldn't register the reminder with the system scheduler."

    routine = None
    try:
        routine = _add_spoken_routine(message, target_dt, reminder_id, task_name,
                                      script_path, os_name, scheduler_id)
    except Exception as exc:
        # Do not leave an OS notification orphaned when its canonical record
        # could not be stored. Roll back the exact task created above.
        _cancel_os_schedule({"task_name": task_name, "scheduler_id": scheduler_id,
                             "os_name": os_name, "script_path": str(script_path)})
        return f"The OS reminder was rolled back because its record could not be saved: {str(exc)[:140]}"

    phone = _mirror_to_cloud(message, target_dt, reminder_id)
    spoken = " It will also be said aloud at that time while the assistant is running." if routine else ""
    if player:
        player.write_log(f"[Reminder] {date_str} {time_str} - {safe_msg[:40]} [{reminder_id}]")
    friendly_time = target_dt.strftime("%B %d at %I:%M %p")
    return f"Reminder set for {friendly_time} (ID {reminder_id}).{spoken}{phone}"

def _mirror_to_cloud(message: str, target_dt: datetime, reminder_id: str = "") -> str:
    """Mirror the reminder to the configured phone channel: Cloudflare/CalDAV
    for Apple Reminders, or Telegram on the legacy paired-cloud path.

    Deterministic on purpose: which of two reminder tools a model happens to
    pick must not decide whether the phone hears about it. Returns a sentence
    to append to the result, or "" when no cloud is paired — in which case this
    costs one config read and changes nothing."""
    try:
        from memory.config_manager import get_plugin_config, get_plugin_enabled
        cfg = get_plugin_config("cloud_agent")
        worker_configured = bool(
            str(cfg.get("worker_url") or "").strip()
            and str(cfg.get("worker_token") or "").strip()
        )
        legacy_configured = bool(str(cfg.get("pair_code") or "").strip())
        if not ((worker_configured or legacy_configured)
                and get_plugin_enabled("cloud_agent")):
            return ""
        agent = sys.modules.get("plugins.cloud_agent")
        if agent is None or not hasattr(agent, "mirror_reminder"):
            return ""
        ok, detail = agent.mirror_reminder(message, target_dt.strftime("%Y-%m-%d %H:%M"), reminder_id=reminder_id)
    except Exception as e:
        ok, detail = False, str(e)
    if ok:
        try:
            from core.routines import desktop
            eng = desktop.engine()
            routine = next((r for r in (eng.list() if eng else [])
                            if r.get("source") == "reminder"
                            and ((r.get("options") or {}).get("jarvis_reminder") or {}).get("id") == reminder_id), None)
            if routine:
                options = dict(routine.get("options") or {})
                meta = dict(options.get("jarvis_reminder") or {})
                meta["cloud_synced"] = True
                options["jarvis_reminder"] = meta
                eng.update(routine["id"], options=options)
        except Exception as exc:
            return f" The phone reminder was created, but its sync link could not be saved locally ({type(exc).__name__}); manage both copies manually."
        if worker_configured:
            return " It will also appear in the JARVIS list in Apple Reminders on your iPhone."
        return " It will also be sent to the user's phone over Telegram at that time."
    return f" The phone copy could not be set ({detail}) — only this computer will remind them."


